def ws_file(name):
    hits = [p for p in WS.rglob(name) if p.is_file()]
    assert len(hits) == 1, hits
    return hits[0].read_text(encoding="latin-1")


def lines(text):
    return [re.sub(r"\s+", "", l) for l in text.replace("\r", "").split("\n") if l.strip() and not STAMP.match(l)]


def _rule(name, kind, line):
    return next((r for r in INTENDED.get(name, []) if r[0] == kind and re.fullmatch(r[1], line)), None)


@pytest.mark.parametrize("name", CODE_FILES)
def test_every_line_matches_the_workspace_except_the_intended_ones(generated, name):
    gen, ws = Counter(lines(generated[name])), Counter(lines(ws_file(name)))
    found, unexplained = Counter(), []
    for kind, diff in (("extra", gen - ws), ("missing", ws - gen)):
        for line, n in diff.items():
            rule = _rule(name, kind, line)
            if rule is None:
                unexplained.append("%s x%d %s" % (kind, n, line))
            else:
                found[rule] += n
    assert not unexplained, "\n".join(sorted(unexplained))
    assert {r: found[r] for r in INTENDED.get(name, [])} == {r: r[2] for r in INTENDED.get(name, [])}


@pytest.mark.parametrize("name", CODE_FILES)
def test_line_order_matches_the_workspace_except_ic2_100(generated, name):
    """Numeric order, NM table entries, frame tables: the same order as the workspace. A line in another place
    shows up as deleted and inserted, which the counted differences do not explain. The IC2_100 signals
    (and the 'break;' lines of their switch cases) are left out: their order is an accepted difference."""
    def ordered(text):
        return [l for l in lines(text) if not IC2_100_ORDER.search(l) and l != "break;"]

    def unexplained(counter):        # lines of the counted differences are checked by the test above
        return Counter({l: n for l, n in counter.items() if not (_rule(name, "extra", l) or _rule(name, "missing", l))})
    a, b = ordered(generated[name]), ordered(ws_file(name))
    deleted, inserted = Counter(), Counter()
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag != "equal":
            deleted.update(a[i1:i2])
            inserted.update(b[j1:j2])
    order_only = ORDER_ONLY.get(name, {})
    assert (unexplained(deleted), unexplained(inserted)) == (
        unexplained(Counter(a) - Counter(b)) + Counter({l: d for l, (d, _, _) in order_only.items()}),
        unexplained(Counter(b) - Counter(a)) + Counter({l: i for l, (_, i, _) in order_only.items()}))
